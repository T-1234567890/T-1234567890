export const normalizeLocalizedPath = (path) => {
  const value = path || "/";
  const withoutIndex = value.replace(/\/index\.html\/?$/i, "");
  const normalized = withoutIndex.replace(/\/+$/, "");
  return normalized || "/";
};

export const stripLanguagePrefix = (path) => {
  const normalized = normalizeLocalizedPath(path);
  if (normalized === "/zh") return "/";
  return normalized.startsWith("/zh/")
    ? normalized.slice(3) || "/"
    : normalized;
};

export const isLocalizedRoute = (path) => {
  const normalized = stripLanguagePrefix(path);
  return (
    normalized === "/" ||
    normalized === "/about" ||
    normalized === "/blog" ||
    /^\/blog\/[^/]+$/.test(normalized) ||
    normalized === "/projects" ||
    normalized === "/privacy" ||
    normalized === "/legal-notices"
  );
};

export const buildLocalizedUrl = (path, lang) => {
  const normalized = stripLanguagePrefix(path);
  const localized =
    lang === "zh"
      ? normalized === "/"
        ? "/zh"
        : `/zh${normalized}`
      : normalized;
  return localized === "/" ? "/" : `${localized}/`;
};

export function initLanguageToggle({ buttonEl }) {
  const storageKey = "lang";

  const writeStored = (lang) => {
    try {
      localStorage.setItem(storageKey, lang);
    } catch {}
  };

  const getLangFromPath = () => {
    const p = normalizeLocalizedPath(window.location.pathname || "/");
    return p === "/zh" || p.startsWith("/zh/") ? "zh" : "en";
  };

  const apply = (lang) => {
    document.documentElement.dataset.lang = lang;
    document.documentElement.lang = lang === "zh" ? "zh-Hans" : "en";

    const dict = I18N[lang] ?? I18N.en;
    for (const node of document.querySelectorAll("[data-i18n]")) {
      const key = node.getAttribute("data-i18n");
      if (!key) continue;
      const next = dict[key];
      if (typeof next === "string") node.textContent = next;
    }

    for (const link of document.querySelectorAll('a[href^="/"]')) {
      const href = link.getAttribute("href");
      if (!href || !isLocalizedRoute(href)) continue;
      link.setAttribute("href", buildLocalizedUrl(href, lang));
    }

    buttonEl.textContent = lang === "zh" ? "EN" : "中文";
    buttonEl.setAttribute("aria-pressed", lang === "zh" ? "true" : "false");
    writeStored(lang);
    document.documentElement.dataset.i18nReady = "true";
  };

  const lang = getLangFromPath();
  apply(lang);

  buttonEl.addEventListener("click", () => {
    const next = getLangFromPath() === "en" ? "zh" : "en";
    writeStored(next);
    window.location.assign(
      buildLocalizedUrl(window.location.pathname || "/", next),
    );
  });
}

export function initHeroScrollTransition({
  heroRootEl,
  heroSentinelEl,
  navSentinelEl,
  navEl,
  onNameEnter,
  onTerminalEnter,
  onInactive,
  terminalEnabled = true,
}) {
  const introEl = document.getElementById("hero-intro");
  const terminalEl = document.getElementById("hero-terminal");

  let currentState = "name";
  const setState = (next) => {
    if (currentState === next) return;
    currentState = next;

    heroRootEl.classList.toggle("state-name", next === "name");
    heroRootEl.classList.toggle("state-terminal", next === "terminal");

    if (introEl) introEl.setAttribute("aria-hidden", next === "terminal" ? "true" : "false");
    if (terminalEl)
      terminalEl.setAttribute("aria-hidden", next === "terminal" ? "false" : "true");

    if (next === "terminal") onTerminalEnter?.();
    else onNameEnter?.();
  };

  const activeObs = new IntersectionObserver(
    (entries) => {
      const entry = entries[0];
      const isActive = Boolean(entry?.isIntersecting);
      heroRootEl.classList.toggle("is-active", isActive);
      if (!isActive) {
        onInactive?.();
        return;
      }

      // If the user scrolls back up into the hero, resume the correct loop.
      if (currentState === "terminal") onTerminalEnter?.();
      else onNameEnter?.();
    },
    { threshold: 0 },
  );
  activeObs.observe(heroRootEl);

  // Swap just the center content (name <-> terminal) based on a sentinel leaving the viewport.
  // This keeps the logo cloud/background static and avoids layout jumps.
  let swapObs = null;
  if (heroSentinelEl) {
    swapObs = new IntersectionObserver(
      (entries) => {
        const entry = entries[0];
        const showName = Boolean(entry?.isIntersecting);
        if (!terminalEnabled) {
          setState("name");
          return;
        }
        setState(showName ? "name" : "terminal");
      },
      { threshold: 0 },
    );
    swapObs.observe(heroSentinelEl);
  }

  const stopNavTransition = initNavCompactTransition({ navSentinelEl, navEl });

  // Initial state sync
  heroRootEl.classList.add("is-active");
  heroRootEl.classList.add("state-name");
  heroRootEl.classList.remove("state-terminal");

  return () => {
    activeObs.disconnect();
    stopNavTransition();
    swapObs?.disconnect();
  };
}

export function initNavCompactTransition({ navSentinelEl, navEl }) {
  let animationFrame = 0;

  const syncNavState = () => {
    animationFrame = 0;
    navEl.classList.toggle(
      "is-compact",
      navSentinelEl.getBoundingClientRect().top <= 0,
    );
  };

  const queueNavStateSync = () => {
    if (animationFrame) return;
    animationFrame = window.requestAnimationFrame(syncNavState);
  };

  syncNavState();
  window.addEventListener("scroll", queueNavStateSync, { passive: true });
  window.addEventListener("resize", queueNavStateSync);

  return () => {
    window.cancelAnimationFrame(animationFrame);
    window.removeEventListener("scroll", queueNavStateSync);
    window.removeEventListener("resize", queueNavStateSync);
  };
}
